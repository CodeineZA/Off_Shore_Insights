// Recipe "eurostat-employers-regional" (method: api): business owners (employers, SELF_S) per region, from Eurostat's regional
// labour force survey (lfst_r_lfe2estat), for the regions whose borders match a NUTS region.
//   node research/fetch-eurostat-regions.mjs   → db/research/eurostat-regions-<date>.sql   (then: bash db/apply.sh <file>)
// Same measure and row format as the national figure (fetch-eurostat.mjs, lfsa_egaps SELF_S): thousands of persons, ref_date 30 June.
// Regions with no matching NUTS region (the three Basque provinces share ES21; Swiss cantons are not NUTS 2) are left out.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const today = new Date().toISOString().slice(0, 10);
const DATASET = 'lfst_r_lfe2estat';
// jurisdiction code → NUTS code (NUTS 2021)
export const NUTS = {
  'BE-BRU': 'BE1', 'BE-VLG': 'BE2', 'BE-WAL': 'BE3',
  'ES-GA': 'ES11', 'ES-AS': 'ES12', 'ES-CB': 'ES13', 'ES-NC': 'ES22', 'ES-RI': 'ES23', 'ES-AR': 'ES24', 'ES-MD': 'ES30', 'ES-CL': 'ES41', 'ES-CM': 'ES42',
  'ES-EX': 'ES43', 'ES-CT': 'ES51', 'ES-VC': 'ES52', 'ES-IB': 'ES53', 'ES-AN': 'ES61', 'ES-MC': 'ES62', 'ES-CE': 'ES63', 'ES-ML': 'ES64', 'ES-CN': 'ES70',
  'IT-21': 'ITC1', 'IT-23': 'ITC2', 'IT-42': 'ITC3', 'IT-25': 'ITC4', 'IT-BZ': 'ITH1', 'IT-TN': 'ITH2', 'IT-34': 'ITH3', 'IT-36': 'ITH4', 'IT-45': 'ITH5',
  'IT-52': 'ITI1', 'IT-55': 'ITI2', 'IT-57': 'ITI3', 'IT-62': 'ITI4', 'IT-65': 'ITF1', 'IT-67': 'ITF2', 'IT-72': 'ITF3', 'IT-75': 'ITF4', 'IT-77': 'ITF5',
  'IT-78': 'ITF6', 'IT-82': 'ITG1', 'IT-88': 'ITG2',
  'PT-20': 'PT20', 'PT-30': 'PT30',
};
const back = Object.fromEntries(Object.entries(NUTS).map(([j, n]) => [n, j]));
const since = new Date().getFullYear() - 6;
const url = `https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/${DATASET}?format=JSON&lang=EN` +
  `&wstatus=SELF_S&sex=T&age=Y15-74&unit=THS_PER&sinceTimePeriod=${since}` + Object.values(NUTS).map((g) => `&geo=${g}`).join('');
const r = await fetch(url);
if (!r.ok) throw new Error(`Eurostat ${r.status}`);
const j = await r.json();
if (!j.dimension) throw new Error('Unexpected Eurostat response: ' + JSON.stringify(j).slice(0, 300));
const dims = j.id, size = j.size;
const idx = (dim, key) => j.dimension[dim].category.index[key];
const rows = [];
for (const g of Object.keys(j.dimension.geo.category.index)) {
  for (const t of Object.keys(j.dimension.time.category.index)) {
    let flat = 0;
    for (let d = 0; d < dims.length; d++) flat = flat * size[d] + (dims[d] === 'geo' ? idx('geo', g) : dims[d] === 'time' ? idx('time', t) : 0);
    const v = j.value[flat];
    if (v === undefined || v === null || !back[g]) continue;
    const flag = j.status?.[flat] ?? '';
    rows.push({ jurisdiction_code: back[g], year: Number(t), business_owners: Math.round(v * 1000),
      // the low-reliability flag ("u") is kept in the source text so it shows wherever the figure is cited
      source: `Eurostat ${DATASET} (SELF_S, ${g})${/u/.test(flag) ? ' low reliability' : ''}`,
      source_url: `https://ec.europa.eu/eurostat/databrowser/view/${DATASET}/default/table`, verified_on: today });
  }
}
if (!rows.length) throw new Error('Eurostat returned no values');
const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const sql = ['-- GENERATED by research/fetch-eurostat-regions.mjs (recipe eurostat-employers-regional) — do not edit.', 'set search_path = offshore_insights;',
  ...rows.map((x) => `insert into wealth_market (jurisdiction_code, year, business_owners, source, source_url, verified_on, ref_date) values (${[x.jurisdiction_code, x.year, x.business_owners, x.source, x.source_url, x.verified_on, `${x.year}-06-30`].map(q).join(', ')}) on conflict (jurisdiction_code, year, source) do update set business_owners = excluded.business_owners, source_url = excluded.source_url, verified_on = excluded.verified_on, ref_date = excluded.ref_date;`),
  'reset search_path;', ''];
mkdirSync(join(here, '..', 'db', 'research'), { recursive: true });
const out = join(here, '..', 'db', 'research', `eurostat-regions-${today}.sql`);
writeFileSync(out, sql.join('\n'));
const missing = Object.keys(NUTS).filter((c) => !rows.some((x) => x.jurisdiction_code === c));
console.log(`wrote ${out}: ${rows.length} rows for ${new Set(rows.map((x) => x.jurisdiction_code)).size} regions; none for: ${missing.join(', ') || '-'}; low reliability: ${rows.filter((x) => /low/.test(x.source)).length}`);
