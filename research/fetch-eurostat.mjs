// Recipe "eurostat-employers" (method: api), run locally without n8n:
//   node research/fetch-eurostat.mjs   → db/research/eurostat-<date>.sql   (then: bash db/apply.sh <file>)
// Reuses the exact extraction of the (paused) n8n E1 node: n8n/src/e1-fetch-eurostat.js.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { targetCountries } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const today = new Date().toISOString().slice(0, 10);
// Target countries (kind = country, not a hub) come from the database; `--countries FR,DE` limits the run.
// Eurostat simply returns nothing for a country it does not cover (UK, South Africa): fetch-ilo.mjs fills those.
const { countries } = await targetCountries();
const COUNTRIES = countries.map((j) => j.code);

const src = readFileSync(join(here, '..', 'n8n', 'src', 'e1-fetch-eurostat.js'), 'utf8');
const node = new Function('$input', `return (async function(){${src}}).call(this)`);
const ctx = { helpers: { httpRequest: async (o) => { const r = await fetch(o.url); if (!r.ok) throw new Error(`Eurostat ${r.status}`); return r.json(); } } };
const [{ json }] = await node.call(ctx, { all: () => COUNTRIES.map((code) => ({ json: { code } })) });

const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const sql = ['-- GENERATED by research/fetch-eurostat.mjs (recipe eurostat-employers) — do not edit.', 'set search_path = offshore_insights;',
  ...json.rows.map((r) => `insert into wealth_market (jurisdiction_code, year, business_owners, source, source_url, verified_on, ref_date) values (${[r.jurisdiction_code, r.year, r.business_owners, r.source, r.source_url, r.verified_on, `${r.year}-06-30`].map(q).join(', ')}) on conflict (jurisdiction_code, year, source) do update set business_owners = excluded.business_owners, source_url = excluded.source_url, verified_on = excluded.verified_on, ref_date = excluded.ref_date;`),
  'reset search_path;', ''];
mkdirSync(join(here, '..', 'db', 'research'), { recursive: true });
const out = join(here, '..', 'db', 'research', `eurostat-${today}.sql`);
writeFileSync(out, sql.join('\n'));
console.log(`wrote ${out}: ${json.count} rows (${[...new Set(json.rows.map((r) => r.jurisdiction_code))].join(', ')})`);
