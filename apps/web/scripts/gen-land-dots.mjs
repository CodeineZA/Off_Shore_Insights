// Pre-computes the design's dotted world map (Claude Design "Coverage map") so the browser
// doesn't download d3 + topojson + the world atlas. Same grid as the design: 720×276
// equirectangular (x = 360 + 2·lon, y = 160 − 2·lat), a 2.6 px square every 5.2 px on land.
import { readFileSync, writeFileSync } from 'node:fs';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const r1 = (v) => Math.round(v * 10) / 10;
let d = '', n = 0;
for (let y = 2; y < 276; y += 5.2) {
  for (let x = 2; x < 720; x += 5.2) {
    const lon = (Math.floor(x) + 0.5 - 360) / 2, lat = (160 - (Math.floor(y) + 0.5)) / 2;
    if (lat > -90 && lat < 90 && geoContains(land, [lon, lat])) { d += `M${r1(x - 1.3)} ${r1(y - 1.3)}h2.6v2.6h-2.6z`; n++; }
  }
}
writeFileSync(new URL('../src/map/landDots.ts', import.meta.url),
  `// GENERATED by scripts/gen-land-dots.mjs (${n} dots) — do not edit.\nexport const LAND_DOTS = '${d}';\n`);
console.log(`wrote src/map/landDots.ts: ${n} dots, ${(d.length / 1024).toFixed(1)} KB`);
